/** Imagen decorativa posicionada por CSS (`project-detail__sport-ball--<modifier>`). */
export interface ProjectDecoration {
  src: string;
  modifier: string;
}

/** Galería con título grande de fondo (texto con degradado). */
export interface TitledGallery {
  title: Localized;
  gradient: string;
  images: string[];
  decorations?: ProjectDecoration[];
}

/**
 * Galería genérica por columnas: cada arreglo interno es una columna y sus
 * imágenes se apilan (sirve para cuadrículas y para columnas de alturas distintas).
 */
export interface ColumnsGallery {
  title: Localized;
  gradient: string;
  columns: string[][];
}

export interface ProjectHeader {
  /** Valor CSS de `background` del encabezado del detalle. */
  background: string;
  /** Brillos decorativos: `project-detail__header-gradient--<nombre>`. */
  gradients?: string[];
  /** Textura que cubre el encabezado con baja opacidad. */
  overlayImage?: string;
  /** Ilustraciones decorativas: `project-detail__header-art--<modifier>`. */
  art?: ProjectDecoration[];
}

export interface Project {
  id: number;
  slug: string;
  title: string;
  /** Título del encabezado del detalle, si difiere del de la tarjeta. */
  detailTitle?: string;
  /** Subtítulo corto de la tarjeta. */
  description: Localized;
  imageSrc: string;
  imageAlt?: string;
  tags?: string[];

  // Encabezado del detalle
  header: ProjectHeader;
  creatorTags?: string[];
  descriptionLong?: Localized;
  meta?: Localized;
  client?: string;
  type?: string;
  software?: string;
  logoSrc?: string;

  // Galerías del detalle (cada una se muestra solo si tiene datos)
  /** Una imagen a todo el ancho y dos a la mitad. */
  galleryMain: [string, string, string];
  galleryMainDecorations?: ProjectDecoration[];
  /** Cinco páginas en tres columnas, bajo el título `layoutTitle`. */
  galleryPro?: [string, string, string, string, string];
  layoutTitle?: Localized;
  galleryMobile?: string[];
  galleryDesign?: TitledGallery;
  galleryWeb?: TitledGallery;
  /** Galerías adicionales, en el orden en que se muestran. */
  galleries?: ColumnsGallery[];
}

